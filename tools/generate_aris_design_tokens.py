#!/usr/bin/env python3
"""Generate Aris Web and native token resources from one JSON source."""

from __future__ import annotations

import argparse
import csv
import io
import json
import re
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT / "design-system" / "tokens" / "aris.tokens.json"
DEFAULT_CSS = ROOT / "src" / "webui" / "src" / "styles" / "harken-search-tokens.generated.css"
DEFAULT_CPP = ROOT / "src" / "HarkenSearchDesignTokens.generated.h"
DEFAULT_FIGMA = ROOT / "design-system" / "figma" / "aris.variables.csv"


def _css_name(token: str) -> str:
    return "--aris-" + token.replace(".", "-")


def _cpp_name(token: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", token)
    return "k" + "".join(part[:1].upper() + part[1:] for part in parts if part)


def _hex_to_rgba(value: str) -> tuple[float, float, float, float]:
    raw = value.removeprefix("#")
    if len(raw) not in (6, 8):
        raise ValueError(f"unsupported color value: {value}")
    if len(raw) == 6:
        raw += "FF"
    channels = tuple(int(raw[index : index + 2], 16) / 255.0 for index in range(0, 8, 2))
    return channels  # type: ignore[return-value]


def _css_scalar(group: str, token: str, value: Any) -> str:
    if group == "metrics" and not token.endswith("alpha"):
        return f"{value:g}px" if isinstance(value, (int, float)) else str(value)
    if group == "typography" and token.startswith("font.size."):
        return f"{value:g}px"
    if group == "motion" and token.endswith(".ms"):
        return f"{value:g}ms"
    return f"{value:g}" if isinstance(value, (int, float)) else str(value)


def render_css(payload: dict[str, Any]) -> str:
    modes = payload["modes"]
    lines = [
        "/* Generated by tools/generate_aris_design_tokens.py. Do not edit. */",
        f"/* Aris Design Tokens {payload['version']} */",
        "",
    ]

    for index, (mode, values) in enumerate(modes.items()):
        selector = (
            f':root, [data-aris-theme="{mode}"]'
            if index == 0
            else f'[data-aris-theme="{mode}"]'
        )
        lines.append(f"{selector} {{")
        for token, value in values.items():
            lines.append(f"  {_css_name(token)}: {value};")
        lines.append("}")
        lines.append("")

    lines.append(":root {")
    for group in ("metrics", "typography", "motion"):
        for token, value in payload[group].items():
            normalized = token.removesuffix(".ms")
            lines.append(
                f"  {_css_name(normalized)}: {_css_scalar(group, token, value)};"
            )
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def render_cpp(payload: dict[str, Any]) -> str:
    dark = payload["modes"]["dark-product"]
    lines = [
        "// Generated by tools/generate_aris_design_tokens.py. Do not edit.",
        "#pragma once",
        "",
        "namespace aris::design {",
        "",
        "struct Rgba {",
        "    float r;",
        "    float g;",
        "    float b;",
        "    float a;",
        "};",
        "",
        f'inline constexpr const char* kVersion = "{payload["version"]}";',
        "",
    ]

    for token, value in dark.items():
        r, g, b, a = _hex_to_rgba(value)
        lines.append(
            f"inline constexpr Rgba {_cpp_name(token)}"
            f"{{{r:.6f}f, {g:.6f}f, {b:.6f}f, {a:.6f}f}};"
        )

    lines.append("")
    for token, value in payload["metrics"].items():
        lines.append(f"inline constexpr float {_cpp_name(token)} = {float(value):.1f}f;")

    lines.extend(["", "} // namespace aris::design", ""])
    return "\n".join(lines)


def render_figma_csv(payload: dict[str, Any]) -> str:
    output = io.StringIO(newline="")
    writer = csv.writer(output, lineterminator="\n")
    writer.writerow(("collection", "mode", "name", "type", "value", "description"))

    mode_labels = {
        "dark-product": "Dark Product",
        "light-documentation": "Light Documentation",
    }
    for mode, values in payload["modes"].items():
        for token, value in values.items():
            writer.writerow(("Color", mode_labels.get(mode, mode), token, "color", value, ""))

    for collection, group in (
        ("Metrics", "metrics"),
        ("Typography", "typography"),
        ("Motion", "motion"),
    ):
        for token, value in payload[group].items():
            value_type = "number" if isinstance(value, (int, float)) else "string"
            writer.writerow((collection, "All", token, value_type, value, ""))
    return output.getvalue()


def _load(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _write_if_changed(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.write_text(content, encoding="utf-8", newline="\n")


def _is_current(path: Path, expected: str) -> bool:
    return path.exists() and path.read_text(encoding="utf-8") == expected


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--css", type=Path, default=DEFAULT_CSS)
    parser.add_argument("--cpp", type=Path, default=DEFAULT_CPP)
    parser.add_argument("--figma", type=Path, default=DEFAULT_FIGMA)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    payload = _load(args.source)
    css = render_css(payload)
    cpp = render_cpp(payload)
    figma_csv = render_figma_csv(payload)

    if args.check:
        stale = [
            str(path)
            for path, expected in ((args.css, css), (args.cpp, cpp), (args.figma, figma_csv))
            if not _is_current(path, expected)
        ]
        if stale:
            print("Generated Aris design tokens are stale:")
            for path in stale:
                print(f"- {path}")
            return 1
        return 0

    _write_if_changed(args.css, css)
    _write_if_changed(args.cpp, cpp)
    _write_if_changed(args.figma, figma_csv)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
