#!/usr/bin/env python3
"""Generate the CJK basic-block Mandarin pinyin lookup table.

Source: Unicode Unihan kMandarin.
Download Unihan.zip from https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip
and pass the extracted Unihan_Readings.txt. The generated file records the
Unicode version and file date from that source header.
"""

from __future__ import annotations

import argparse
from pathlib import Path

TONELESS = str.maketrans({
    "ā": "a", "á": "a", "ǎ": "a", "à": "a",
    "ē": "e", "é": "e", "ě": "e", "è": "e",
    "ī": "i", "í": "i", "ǐ": "i", "ì": "i",
    "ō": "o", "ó": "o", "ǒ": "o", "ò": "o",
    "ū": "u", "ú": "u", "ǔ": "u", "ù": "u",
    "ǖ": "v", "ǘ": "v", "ǚ": "v", "ǜ": "v", "ü": "v",
    "ń": "n", "ň": "n", "ǹ": "n",
    "ḿ": "m",
})
BLOCK_FIRST = 0x4E00
BLOCK_LAST = 0x9FFF


def source_identity(lines: list[str]) -> tuple[str, str]:
    version = "unknown"
    dated = "unknown"
    for line in lines[:12]:
        if line.startswith("# Unicode Version "):
            version = line.removeprefix("# Unicode Version ").strip()
        elif line.startswith("# Date: "):
            dated = line.removeprefix("# Date: ").split(" GMT", 1)[0].strip()
    return version, dated


def readings(lines: list[str]) -> list[str | None]:
    span = BLOCK_LAST - BLOCK_FIRST + 1
    table: list[str | None] = [None] * span
    for line in lines:
        if not line or line[0] == "#":
            continue
        parts = line.split("\t")
        if len(parts) != 3 or parts[1] != "kMandarin":
            continue
        codepoint = int(parts[0][2:], 16)
        if codepoint < BLOCK_FIRST or codepoint > BLOCK_LAST:
            continue
        syllable = parts[2].split()[0].lower().translate(TONELESS)
        if not syllable.isascii() or not syllable.isalpha():
            raise SystemExit(f"unsupported reading {parts[2]!r} for {parts[0]}")
        table[codepoint - BLOCK_FIRST] = syllable
    return table


def c_bytes(name: str, data: bytes) -> str:
    rows = []
    for start in range(0, len(data), 16):
        chunk = ", ".join(f"0x{byte:02x}" for byte in data[start:start + 16])
        rows.append(f"    {chunk},")
    return f"static const unsigned char {name}[] = {{\n" + "\n".join(rows) + "\n};"


def render(table: list[str | None], version: str, dated: str) -> str:
    unique = sorted({item for item in table if item})
    indexes = {item: index for index, item in enumerate(unique)}
    pool = bytearray()
    for item in unique:
        pool.extend(item.encode("ascii") + b"\0")
    entries = bytearray()
    for item in table:
        value = 0xFFFF if item is None else indexes[item]
        entries.extend((value & 0xFF, value >> 8))
    return f"""// Generated by tools/generate_mandarin_pinyin_table.py. Do not edit by hand.
// Source: Unicode Unihan kMandarin, Unicode {version}, file date {dated}.
// CJK Unified Ideographs U+4E00..U+9FFF. First listed reading only.
// Tone marks removed. u-umlaut stored as v. 0xFFFF means no reading.
static constexpr uint32_t kMandarinPinyinBase = 0x4E00u;
static constexpr uint32_t kMandarinPinyinCount = {len(table)}u;
static constexpr uint16_t kMandarinPinyinMissing = 0xFFFFu;

{c_bytes("kMandarinSyllablePool", bytes(pool))}

{c_bytes("kMandarinPinyinEntries", bytes(entries))}
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("readings", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    lines = args.readings.read_text(encoding="utf-8").splitlines()
    version, dated = source_identity(lines)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(readings(lines), version, dated), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
