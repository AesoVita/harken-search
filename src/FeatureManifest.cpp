
// FeatureManifest.cpp — 运行时功能裁剪（HMAC-SHA256 验证）

// Key obfuscation: kKeyXored[i] = realKey[i] ^ kKeyMask[i]
// kKeyXored is patched by tools/gen_manifest_key.py at build preparation time.
// kKeyMask is a fixed random mask hardcoded here.
//
// Verification flow:
//   1. Read harken_features.json (raw bytes)
//   2. Read harken_features.sig  (exactly 32 bytes)
//   3. Derive HMAC key from kKeyXored ^ kKeyMask
//   4. Compute HMAC-SHA256(key, jsonBytes)
//   5. Constant-time compare with .sig
//   6. If match: parse enabled_features into g_enabledFeatures, set g_verified
//   7. Zero the key from stack immediately after use
//
// Non-Windows / HMAC provider unavailable: the PAL returns Unsupported →
//   loadAndVerify() returns false → isEnabled() always returns true.

#include "FeatureManifest.h"
#include "platform/harken_user_data_layout.h"
#include "platform/filesystem.h"
#include "platform/hmac_sha256.h"

#include <string>
#include <unordered_set>
#include <vector>
#include <cstring>

// Key storage — XOR-obfuscated

// Fixed random mask (never changes — part of source)
static const uint8_t kKeyMask[32] = {
    0xA3, 0x7B, 0x12, 0xF0, 0x9E, 0x44, 0xD1, 0x88,
    0x56, 0x2C, 0xE7, 0x3A, 0x01, 0xBD, 0x65, 0xC9,
    0x70, 0x4F, 0x8D, 0x23, 0xAA, 0x17, 0x5E, 0xF6,
    0xDB, 0x39, 0x82, 0x04, 0x6B, 0xC1, 0x58, 0x9F,
};

// XOR'd key bytes — patched by tools/gen_manifest_key.py
// All zeros = placeholder (no manifest enforcement until patched)
// GEN_MANIFEST_KEY_BEGIN
static const uint8_t kKeyXored[32] = {
    0xBE, 0xF0, 0x7F, 0x27, 0xCF, 0x2C, 0x63, 0xBE,
    0xD5, 0x7F, 0x5F, 0x3E, 0xC9, 0xFA, 0xC5, 0x0E,
    0x97, 0x34, 0x6E, 0xDA, 0xF3, 0x62, 0x46, 0xBE,
    0xC4, 0x16, 0x52, 0xA1, 0x80, 0x2A, 0x25, 0x2F,
};
// GEN_MANIFEST_KEY_END

// Derive the real key from obfuscated storage.
// Caller must zero the output buffer after use.
static void deriveKey(uint8_t out[32]) {
    for (int i = 0; i < 32; ++i) {
        out[i] = kKeyXored[i] ^ kKeyMask[i];
    }
}

// Utilities

// Read entire file into a byte vector. Returns empty on error.
static std::vector<uint8_t> readFile(const std::string& path) {
    return Platform::FileSystem::ReadFileBytes(path);
}

// Constant-time comparison to prevent timing attacks.
static bool secureCompare(const uint8_t* a, const uint8_t* b, size_t len) {
    volatile uint8_t diff = 0;
    for (size_t i = 0; i < len; ++i) {
        diff |= a[i] ^ b[i];
    }
    return diff == 0;
}

// Minimal JSON parser — only handles "enabled_features":[...]
// We control the format (generated by pack tool), so a full parser is overkill.

static std::unordered_set<std::string> parseEnabledFeatures(
    const std::vector<uint8_t>& jsonBytes)
{
    std::unordered_set<std::string> result;

    // Convert to string view for searching
    const char* s = reinterpret_cast<const char*>(jsonBytes.data());
    size_t len = jsonBytes.size();
    std::string json(s, len);

    // Find "enabled_features"
    const std::string kKey = "\"enabled_features\"";
    auto pos = json.find(kKey);
    if (pos == std::string::npos) return result;
    pos += kKey.size();

    // Skip whitespace and colon
    while (pos < len && (json[pos] == ' ' || json[pos] == '\t' ||
                         json[pos] == '\r' || json[pos] == '\n')) ++pos;
    if (pos >= len || json[pos] != ':') return result;
    ++pos;

    // Skip whitespace
    while (pos < len && (json[pos] == ' ' || json[pos] == '\t' ||
                         json[pos] == '\r' || json[pos] == '\n')) ++pos;
    if (pos >= len || json[pos] != '[') return result;
    ++pos;

    // Extract quoted strings until ']'
    while (pos < len) {
        // Skip whitespace and commas
        while (pos < len && (json[pos] == ' ' || json[pos] == '\t' ||
                              json[pos] == '\r' || json[pos] == '\n' ||
                              json[pos] == ',')) ++pos;

        if (pos >= len) break;
        if (json[pos] == ']') break;

        if (json[pos] == '"') {
            ++pos;  // skip opening quote
            size_t start = pos;
            while (pos < len && json[pos] != '"') {
                // Handle escape sequences (skip \")
                if (json[pos] == '\\' && pos + 1 < len) ++pos;
                ++pos;
            }
            if (pos <= len) {
                result.insert(json.substr(start, pos - start));
            }
            if (pos < len) ++pos;  // skip closing quote
        } else {
            // Unexpected character — skip
            ++pos;
        }
    }

    return result;
}

// Module state

static bool g_loaded   = false;
static bool g_verified = false;
static std::unordered_set<std::string> g_enabledFeatures;

// Public API

namespace FeatureManifest {

bool loadAndVerify(const std::string& exeDir) {
    g_loaded   = false;
    g_verified = false;
    g_enabledFeatures.clear();

    // Build paths
    std::string sep = (exeDir.empty() || exeDir.back() == '/' ||
                       exeDir.back() == '\\') ? "" : "\\";
    using Platform::HarkenUserData::CanonicalFeaturesJsonFileName;
    using Platform::HarkenUserData::CanonicalFeaturesSigFileName;
    using Platform::HarkenUserData::LegacyArisFeaturesJsonFileName;
    using Platform::HarkenUserData::LegacyArisFeaturesSigFileName;
    using Platform::HarkenUserData::LegacyAuroFeaturesJsonFileName;
    using Platform::HarkenUserData::LegacyAuroFeaturesSigFileName;
    const char* names[][2] = {
        {CanonicalFeaturesJsonFileName(), CanonicalFeaturesSigFileName()},
        {LegacyArisFeaturesJsonFileName(), LegacyArisFeaturesSigFileName()},
        {LegacyAuroFeaturesJsonFileName(), LegacyAuroFeaturesSigFileName()},
    };
    std::string jsonPath;
    std::string sigPath;
    std::vector<uint8_t> jsonBytes;
    std::vector<uint8_t> sigBytes;
    // Prefer the current filename, then silently read older shipped names.
    for (const auto& pair : names) {
        jsonPath = exeDir + sep + pair[0];
        sigPath = exeDir + sep + pair[1];
        jsonBytes = readFile(jsonPath);
        sigBytes = readFile(sigPath);
        if (!jsonBytes.empty() && sigBytes.size() == 32) break;
    }

    if (jsonBytes.empty()) {
        // Missing manifest → fallback mode (no restriction)
        return false;
    }

    // Signature must be exactly 32 bytes for HMAC-SHA256.
    if (sigBytes.size() != 32) {
        // Missing or malformed sig → fallback
        return false;
    }

    // Derive key
    uint8_t key[32] = {};
    deriveKey(key);

    // Compute HMAC-SHA256
    const auto hmac = Platform::Crypto::ComputeHmacSha256(
        key, sizeof(key), jsonBytes.data(), jsonBytes.size());
    memset(key, 0, sizeof(key));

    if (hmac.status != Platform::Crypto::HmacSha256Status::Success) {
        // HMAC unavailable or failed → fallback
        return false;
    }

    // Constant-time compare
    if (!secureCompare(hmac.digest.data(), sigBytes.data(), hmac.digest.size())) {
        // Signature mismatch → tampered or wrong key → fallback
        return false;
    }

    // Signature verified — parse enabled_features
    g_enabledFeatures = parseEnabledFeatures(jsonBytes);
    g_loaded   = true;
    g_verified = true;
    return true;
}

bool isEnabled(const char* featureId) {
    if (!featureId) return true;
    // If manifest not loaded or not verified, don't restrict anything
    // (Edition layer handles the ceiling)
    if (!g_loaded || !g_verified) return true;
    return g_enabledFeatures.count(featureId) > 0;
}

bool isLoaded() {
    return g_loaded && g_verified;
}

} // namespace FeatureManifest
